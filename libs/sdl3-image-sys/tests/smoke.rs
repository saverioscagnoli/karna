use sdl3_image_sys::*;
use sdl3_sys::*;

/// A 1x1 transparent PNG.
const PNG_1X1: &[u8] = &[
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
    0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
    0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
    0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
];

#[test]
fn links_and_reports_version() {
    let v = unsafe { IMG_Version() };
    let major = v / 1_000_000;
    let minor = (v / 1_000) % 1_000;
    assert_eq!(major, 3, "expected SDL3_image, got version {v}");
    println!("linked against SDL_image {major}.{minor}.{}", v % 1_000);
}

#[test]
fn decodes_png_from_memory() {
    unsafe {
        let io = SDL_IOFromConstMem(PNG_1X1.as_ptr().cast(), PNG_1X1.len());
        assert!(!io.is_null(), "SDL_IOFromConstMem failed");

        let surface = IMG_Load_IO(io, true);
        assert!(!surface.is_null(), "IMG_Load_IO failed: {}", get_error());

        assert_eq!(((*surface).w, (*surface).h), (1, 1));
        SDL_DestroySurface(surface);
    }
}
